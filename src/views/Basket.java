    /**
     * Constructor for Basket.
     * @param cr the logged in customer
     * @param o the current order containing order lines to display
     */
    public Basket(Customer cr, Order o) 
    {
        // store constructor parameters in instance fields
        loggedInCustomer = cr;
        currentOrder = o;
        
        initComponents();
        
        // get the table model so we can add rows to the basket table
        DefaultTableModel basketModel = (DefaultTableModel)tblBasket.getModel();
        // iterate through each order line in the current order and add a row
        for(Map.Entry<Integer, OrderLine> olMapEntry : currentOrder.getOrderLines().entrySet())
        {
            OrderLine actualOrderLine = olMapEntry.getValue();
            
            // add a row: productId, productName, price, quantity
            basketModel.addRow(new Object[] {
            actualOrderLine.getproduct().getproductId(),
            actualOrderLine.getproduct().getproductName(),
            "£" + actualOrderLine.getlineTotal(),
            //"£" + actualOrderLine.getlineTotal(),
            actualOrderLine.getquantity()
            });
        }
        
        // reassign the model back to the table (ensures table shows added rows)
        tblBasket.setModel(basketModel);
    }

