    private void btnBuyActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnBuyActionPerformed
        // Set the order status to "Order Placed"
        currentOrder.setStatus("Order Placed");
        
        // Create database manager instance
        DBManager db = new DBManager();
        
        // Write the order to database and get the generated order ID
        int orderId = db.writeOrder(currentOrder, loggedInCustomer.getUsername());
        
        // Iterate through all order lines in the current order
        for(Map.Entry<Integer, OrderLine> olMapEntry : currentOrder.getOrderLines().entrySet())
        {
            OrderLine actualOrderLine = olMapEntry.getValue();
            
            db.updateProductStockLevel(actualOrderLine.getproduct().getproductId(), actualOrderLine.getquantity());
            
            // Write each order line to database with the order
            db.writeOrderLine(actualOrderLine, orderId);
        }
        
        // Show confirmation page and hide current basket window
        ConfirmationPage confirmation = new ConfirmationPage(loggedInCustomer, currentOrder);
        confirmation.setVisible(true);
        this.setVisible(false);
    }//GEN-LAST:event_btnBuyActionPerformed

