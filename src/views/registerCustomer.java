    private void btnSubmitActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSubmitActionPerformed
        //check for empty fields
        // Check if any fields are empty
        if (txtUsername.getText().isEmpty()
                || txtPassword.getText().isEmpty()
                || txtFirstname.getText().isEmpty()
                || txtLastname.getText().isEmpty()
                || txtHouseNumber.getText().isEmpty()
                || txtStreet.getText().isEmpty()
                || txtTown.getText().isEmpty()
                || txtPostcode.getText().isEmpty()) {
            lblConfirmation.setText("Error: All fields must be filled!");
        } 
        
        else {

            try {
                // Retrieve and parse input values from text fields
                String username = txtUsername.getText();
                String password = txtPassword.getText();
                String firstname = txtFirstname.getText();
                String lastname = txtLastname.getText();
                String houseNumber = txtHouseNumber.getText();
                String street = txtStreet.getText();
                String town = txtTown.getText();
                String postcode = txtPostcode.getText();

                //create customer
                Customer c = new Customer(username, password, firstname, lastname, houseNumber, street, town, postcode);

                //register customer
                DBManager db = new DBManager();
                boolean register = db.regiserCustomer(c);
                if (register == true) {
                    lblConfirmation.setText("New Customer Registered");
                } else {
                    lblConfirmation.setText("Username already in use");
                }

            } catch (Exception ext) {
                lblConfirmation.setText("Error: Couldn't Register User");
            }
        }
    }//GEN-LAST:event_btnSubmitActionPerformed

