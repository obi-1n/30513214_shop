    private void btnSubmitActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSubmitActionPerformed
        //check for empty fields
        // Check if any fields are empty
        if(txtHouseNumber.getText().isEmpty() || 
           txtStreet.getText().isEmpty() || 
           txtTown.getText().isEmpty() ||
           txtPostcode.getText().isEmpty())
        {
            lblConfirmation.setText("Error: All fields must be filled!");
            return;
        }
        
        try {
            // Retrieve and parse input values from text fields
            String houseNumber = txtHouseNumber.getText();
            String street = txtStreet.getText();
            String town = txtTown.getText();
            String postcode = txtPostcode.getText();

            // Update the users details with new values
            loggedInCustomer.setaddressLine1(houseNumber);
            loggedInCustomer.setaddressLine2(street);
            loggedInCustomer.settown(town);
            loggedInCustomer.setpostcode(postcode);

            DBManager db = new DBManager();
            db.editDetails(loggedInCustomer);
            lblConfirmation.setText("Details Updated Successfully");
        } catch (Exception ext) {
            lblConfirmation.setText("Error: Couldn't Update User Details");
        }
    }//GEN-LAST:event_btnSubmitActionPerformed

