    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
        
        //check for empty fields
        // Check if any fields are empty
        if(txtProductName.getText().isEmpty() || 
           txtPrice.getText().isEmpty() || 
           txtStockLevel.getText().isEmpty() || 
           txtExtraAttribute.getText().isEmpty())
        {
            lblConfirmation.setText("Error: All fields must be filled!");
            return;
        }
        
        try {
            // Retrieve and parse input values from text fields
            String name = txtProductName.getText();
            double price = Double.parseDouble(txtPrice.getText());
            int stockLevel = Integer.parseInt(txtStockLevel.getText());

            // Update the current product with new values
            currentProduct.setproductName(name);
            currentProduct.setprice(price);
            currentProduct.setstockLevel(stockLevel);

            // Handle product-specific attributes based on type
            //Clothing
            if (currentProduct.getClass().getName().equals("models.Clothing")) {
            Clothing c = (Clothing) currentProduct;
            String measurement = txtExtraAttribute.getText();
                c.setmeasurement(measurement);

            //Footwear
            } else if (currentProduct.getClass().getName().equals("models.Footwear")) {
                Footwear f = (Footwear) currentProduct;
                int size = Integer.parseInt(txtExtraAttribute.getText());
                f.setsize(size);
            }
            DBManager db = new DBManager();
            db.editProduct(currentProduct);
            lblConfirmation.setText("Product Updated Successfully");
        } catch (Exception ext) {
            lblConfirmation.setText("Error: Price, Stock level and Size must be numberic!");
        }
        
        
    }//GEN-LAST:event_jButton1ActionPerformed

